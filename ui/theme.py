def _srgb_channel(value: int) -> float:
    channel = value / 255.0
    return channel / 12.92 if channel <= 0.03928 else ((channel + 0.055) / 1.055) ** 2.4


def relative_luminance(hex_color: str) -> float:
    hex_color = hex_color.lstrip("#")
    r, g, b = (int(hex_color[i : i + 2], 16) for i in (0, 2, 4))
    r, g, b = _srgb_channel(r), _srgb_channel(g), _srgb_channel(b)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast_ratio(hex_a: str, hex_b: str) -> float:
    """WCAG 2.x contrast ratio between two colours, 1.0 (none) to 21.0 (max)."""
    lum_a, lum_b = relative_luminance(hex_a), relative_luminance(hex_b)
    lighter, darker = max(lum_a, lum_b), min(lum_a, lum_b)
    return (lighter + 0.05) / (darker + 0.05)


def build_config_toml() -> str:
    """.streamlit/config.toml content, generated from COLORS -- regenerate
    with scripts/build_streamlit_config.py after changing a token here."""
    c = COLORS
    return (
        "[theme]\n"
        'base = "light"\n'
        f'primaryColor = "{c["primary"]}"\n'
        f'backgroundColor = "{c["page_bg"]}"\n'
        f'secondaryBackgroundColor = "{c["surface"]}"\n'
        f'textColor = "{c["ink"]}"\n'
        f'font = "{FONT_CONFIG_VALUE}"\n'
        f'codeFont = "{CODE_FONT_CONFIG_VALUE}"\n'
        f'borderColor = "{c["line"]}"\n'
        f'baseRadius = "{RADII_PX["control"]}px"\n'
        f'buttonRadius = "{RADII_PX["control"]}px"\n'
        f'linkColor = "{c["primary"]}"\n'
        f'redColor = "{c["error"]}"\n'
        f'greenColor = "{c["success"]}"\n'
        "\n"
        "[client]\n"
        'toolbarMode = "minimal"\n'
        "\n"
        "[server]\n"
        # 50, not 10: matches the app's OWN pre-existing PDF size cap
        # (ui/components/uploads.py::MAX_PDF_SIZE_BYTES = 50 MB, which the
        # reference's own error copy also quotes -- "fichier .pdf de 50 Mo
        # maximum"). Streamlit's maxUploadSize is a single global server
        # cap (no per-uploader override), so setting it to 10 to match the
        # IMAGE uploader's 10 MB rule would silently break PDF uploads
        # between 10-50 MB, a real regression for a config.toml value whose
        # only visible symptom was a stale default of 200 MB. The French
        # "10 Mo max" copy for images is enforced by our own app-level
        # validation (MAX_IMAGE_SIZE_BYTES) regardless of this server cap;
        # Streamlit's own (now-correct, just more permissive) default
        # caption is hidden via CSS below so there's no conflicting number
        # shown to the user.
        "maxUploadSize = 50\n"
    )


