"""Design tokens for the "Technicien" design system (validated by the user).

Single source of truth: `.streamlit/config.toml` (regenerated by
scripts/build_streamlit_config.py) and the injected stylesheet are both
generated from the tokens below, so there is exactly one place to change a
colour, font, spacing or radius value.

Bug fix (section 0a of the UI-redesign task, round 1): the previous
stylesheet had a `[class*="st-"]` font-family rule that also matched the
span Streamlit uses to render Material Symbols icons, overriding the icon
font with the UI font and making icon names show up as literal text
("upload", "face", ...). The global UI font is now set ONLY via
`.streamlit/config.toml`'s `font` key (which Streamlit itself scopes
correctly, leaving icon fonts alone) -- `build_css()` below never sets a
blanket `font-family` on `html`/`body`/`*` or any `[class*=...]` wildcard,
only on our own named classes.

Bug fix (section 0a, round 2 -- the real cause of "theme not applied at
all, dark + Streamlit red everywhere"): `font`/`codeFont` in config.toml
each pointed at the SAME Google Fonts URL, which requested BOTH
`IBM+Plex+Sans` and `JetBrains+Mono` in one query string
(`family=...&family=...`). Streamlit's own theme parser
(`streamlit/runtime/theme_util.py::_parse_font_config`) rejects any
font/codeFont source URL containing more than one `family=` occurrence
with `StreamlitInvalidThemeOptionError`, which happens while the server is
starting and aborts loading the custom [theme] section entirely -- so the
app silently fell all the way back to Streamlit's built-in default theme
(dark-if-OS-prefers-dark, red `#FF4B4B` accents), not just a missing font.
Each of `font`/`codeFont` now points at its OWN single-family URL
(`FONT_SOURCE_URL`/`CODE_FONT_SOURCE_URL`); `tests/test_theme.py` feeds the
generated config.toml through Streamlit's real parser
(`streamlit.runtime.theme_util.parse_fonts_with_source`) so a regression
here fails a test instead of silently falling back again. `base = "light"`
is also set explicitly so the app stays light even when the OS/browser
prefers dark (Streamlit otherwise lets `prefers-color-scheme` pick a
built-in base when a custom theme doesn't nail down every value).
"""

